const dictionaries: Record<Locale, CommonDictionary> = { en, de };

/** Replaces {name} placeholders. */
export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

export function seatsLabel(dict: CommonDictionary, n: number): string {
  return n === 1 ? dict.common.seatLeft : fill(dict.common.seatsLeft, { n });
}

export function commonDictionary(locale: Locale): CommonDictionary {
  return dictionaries[locale];
}
