/**
 * Builds the static showcase for Cloudflare Workers (free plan, no server, no database):
 *   bun scripts/build-showcase.ts        (the local database must be running: bun run db)
 *
 * 1. `next build` with NEXT_PUBLIC_SHOWCASE=1 (into .next-showcase, forms in demo mode).
 * 2. Serves that build on a spare port and crawls every public page in English and German.
 * 3. Writes showcase-site/ (HTML, /_next/static, /public files, 404, _redirects, _headers),
 *    which wrangler.jsonc deploys as static assets.
 */
import { spawn, spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

const OUT = "showcase-site";
const PORT = 4310;
const BASE = `http://127.0.0.1:${PORT}`;
const env = { ...process.env, NEXT_PUBLIC_SHOWCASE: "1", NEXT_TELEMETRY_DISABLED: "1", NEXT_BUILD_CPUS: process.env.NEXT_BUILD_CPUS ?? "2" };
const log = (m: string) => console.log(`[showcase] ${m}`);

if (!process.argv.includes("--skip-build")) {
  log("building (NEXT_PUBLIC_SHOWCASE=1) …");
  const b = spawnSync("bun", ["--bun", "next", "build"], { stdio: "inherit", env, shell: process.platform === "win32" });
  if (b.status !== 0) process.exit(b.status ?? 1);
}

log(`serving the build on ${BASE}`);
const server = spawn("bun", ["--bun", "next", "start", "--hostname", "127.0.0.1", "--port", String(PORT)], { env, shell: process.platform === "win32" });
const stop = () => {
  if (process.platform === "win32") spawnSync("taskkill", ["/PID", String(server.pid), "/T", "/F"]);
  else server.kill();
};
for (let i = 0; ; i++) {
  try {
    if ((await fetch(`${BASE}/api/health`)).ok) break;
  } catch {}
  if (i > 90) { stop(); throw new Error("showcase server did not start"); }
  await new Promise((r) => setTimeout(r, 1000));
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

// Crawl: start from both homepages and the sitemap, follow internal links to public pages.
const sitemap = await (await fetch(`${BASE}/sitemap.xml`)).text();
const queue = new Set<string>(["/en", "/de", "/en/missing", "/de/missing"]);
for (const m of sitemap.matchAll(/<loc>https?:\/\/[^/]+(\/[^<]*)<\/loc>/g)) queue.add(m[1]);
for (const m of sitemap.matchAll(/hreflang="de" href="https?:\/\/[^/]+(\/[^"]*)"/g)) queue.add(m[1]);
const done = new Set<string>();
const PUBLIC = /^\/(en|de)(\/[a-z0-9\-/]*)?$/;
const SKIP = /^\/(en|de)\/newsletter\/confirm/;
const media = new Set<string>();

while (queue.size) {
  const [p] = queue;
  queue.delete(p);
  if (done.has(p)) continue;
  done.add(p);
  const res = await fetch(BASE + p, { redirect: "manual" });
  if (res.status !== 200) { log(`skip ${p} (${res.status})`); continue; }
  const html = await res.text();
  const file = path.join(OUT, `${p}.html`); // served at the address without a trailing slash
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, html);
  for (const m of html.matchAll(/href="(\/(?:en|de)[^"#?]*)/g)) {
    const link = m[1].replace(/\/$/, "");
    if (PUBLIC.test(link) && !SKIP.test(link) && !done.has(link)) queue.add(link);
  }
  for (const m of html.matchAll(/(?:href|src)="(\/media\/[0-9a-f-]{36})"/g)) media.add(m[1]);
}
log(`saved ${done.size} pages`);

// Files generated by route handlers (icons, manifest) and images uploaded through the admin.
for (const p of ["/site.webmanifest", "/icon.svg", "/apple-icon.png", "/favicon.ico", "/robots.txt", ...media]) {
  const res = await fetch(BASE + p);
  if (!res.ok) { log(`skip ${p} (${res.status})`); continue; }
  const file = path.join(OUT, p);
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, Buffer.from(await res.arrayBuffer()));
}

// Not-found page (served by Workers for unknown paths).
writeFileSync(path.join(OUT, "404.html"), await (await fetch(`${BASE}/en/missing`)).text());
stop();

// Static files: build assets and everything in /public except the offline worker.
cpSync(".next-showcase/static", path.join(OUT, "_next", "static"), { recursive: true });
cpSync("public", OUT, { recursive: true, filter: (src) => !src.endsWith(`${path.sep}sw.js`) && !src.endsWith("offline.html") });
if (!existsSync(path.join(OUT, "en.html"))) throw new Error("homepage missing from the crawl");

writeFileSync(
  path.join(OUT, "_redirects"),
  ["/ /en 302", "/courses /en/courses 302", "/events /en/events 302", "/contact /en/contact 302", "/admin /en 302", "/admin/* /en 302", ""].join("\n"),
);
writeFileSync(
  path.join(OUT, "_headers"),
  [
    "/*",
    "  X-Robots-Tag: noindex, nofollow",
    "  X-Content-Type-Options: nosniff",
    "  X-Frame-Options: DENY",
    "  Referrer-Policy: strict-origin-when-cross-origin",
    "  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=()",
    "  Strict-Transport-Security: max-age=31536000",
    "/_next/static/*",
    "  Cache-Control: public, max-age=31536000, immutable",
    "/images/*",
    "  Cache-Control: public, max-age=604800, stale-while-revalidate=86400",
    "/brand/*",
    "  Cache-Control: public, max-age=604800, stale-while-revalidate=86400",
    "/showcase/*",
    "  Cache-Control: public, max-age=604800, stale-while-revalidate=86400",
    "",
  ].join("\n"),
);
log(`done: ${OUT}/ is ready for \`npx wrangler deploy\``);
