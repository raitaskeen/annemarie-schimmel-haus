/**
 * One-command local environment.
 *
 *   bun run local          → Postgres + migrations + seed + `next dev` on :4000
 *   bun run local:start    → Postgres + migrations + `next start` (after `bun run build`)
 *   bun run db             → only Postgres (keep running for builds/tests)
 *   bun run db:migrate     → apply migrations to DATABASE_URL and exit
 *
 * Postgres 17 runs from the `embedded-postgres` package (real server binaries,
 * no Docker). Data lives in .data/postgres. On first run a .env.local file is
 * created with fresh random secrets and a first admin account.
 */
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import net from "node:net";
import path from "node:path";
import { spawn, type ChildProcess } from "node:child_process";
import EmbeddedPostgres from "embedded-postgres";
import { Client } from "pg";
import { drizzle } from "drizzle-orm/node-postgres";
import { migrate } from "drizzle-orm/node-postgres/migrator";
import { generatePassword } from "../src/lib/auth/password";

const ROOT = path.resolve(import.meta.dirname, "..");
const ENV_FILE = path.join(ROOT, ".env.local");
const DATA_DIR = path.join(ROOT, ".data", "postgres");
const APP_PORT = Number(process.env.PORT ?? 4000);

const mode = (process.argv[2] ?? "dev") as "dev" | "start" | "db" | "migrate" | "seed" | "reset-seed";

function log(message: string) {
  console.log(`\x1b[32m[ash]\x1b[0m ${message}`);
}

/* ------------------------------------------------------------------ env file */

function parseEnv(source: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of source.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (!m) continue;
    out[m[1]] = m[2].replace(/^"(.*)"$/, "$1");
  }
  return out;
}

function ensureEnvFile() {
  if (!existsSync(ENV_FILE)) {
    const dbPassword = randomBytes(18).toString("base64url");
    const adminPassword = generatePassword(20);
    const contents = [
      "# Generated by scripts/local.ts for local development only. Never commit this file.",
      `LOCAL_DB_PORT=54777`,
      `LOCAL_DB_PASSWORD=${dbPassword}`,
      `DATABASE_URL=postgres://ash:${dbPassword}@127.0.0.1:54777/ash`,
      `AUTH_SECRET=${randomBytes(48).toString("base64url")}`,
      `CRON_SECRET=${randomBytes(32).toString("base64url")}`,
      `APP_URL=http://localhost:${APP_PORT}`,
      `STAFF_NOTIFY_EMAIL=office@schimmel.local`,
      "",
      "# First administrator (created by the seed if no admin exists yet).",
      `SEED_ADMIN_EMAIL=admin@schimmel.local`,
      `SEED_ADMIN_NAME="Site Administrator"`,
      `SEED_ADMIN_PASSWORD="${adminPassword}"`,
      "",
      "# Optional integrations — see README.md",
      "# GMAIL_CLIENT_ID=",
      "# GMAIL_CLIENT_SECRET=",
      "# GMAIL_REFRESH_TOKEN=",
      "# GMAIL_SENDER=info@schimmel.com.pk",
      "# WHATSAPP_TOKEN=",
      "# WHATSAPP_PHONE_NUMBER_ID=",
      "# WHATSAPP_APP_SECRET=",
      "# WHATSAPP_VERIFY_TOKEN=",
      "",
    ].join("\n");
    writeFileSync(ENV_FILE, contents, { encoding: "utf8", mode: 0o600 });
    log("Created .env.local with fresh local secrets.");
  }
  const parsed = parseEnv(readFileSync(ENV_FILE, "utf8"));
  for (const [k, v] of Object.entries(parsed)) process.env[k] ??= v;
}

/* ------------------------------------------------------------------- postgres */

function portInUse(port: number): Promise<boolean> {
  return new Promise((resolve) => {
    const socket = net.connect({ port, host: "127.0.0.1" });
    socket.once("connect", () => {
      socket.destroy();
      resolve(true);
    });
    socket.once("error", () => resolve(false));
  });
}

async function startPostgres(): Promise<EmbeddedPostgres | null> {
  const port = Number(process.env.LOCAL_DB_PORT ?? 54777);
  const password = process.env.LOCAL_DB_PASSWORD;
  if (!password) throw new Error("LOCAL_DB_PASSWORD is missing from .env.local");

  if (await portInUse(port)) {
    // Only reuse the server if it is ours (accepts our credentials).
    const probe = new Client({ host: "127.0.0.1", port, user: "ash", password, database: "postgres" });
    try {
      await probe.connect();
      await probe.end();
    } catch {
      throw new Error(
        `Port ${port} is used by another service. Set LOCAL_DB_PORT and DATABASE_URL in .env.local to a free port.`,
      );
    }
    log(`Postgres already running on 127.0.0.1:${port} — reusing it.`);
    return null;
  }

  mkdirSync(path.dirname(DATA_DIR), { recursive: true });
  const pg = new EmbeddedPostgres({
    databaseDir: DATA_DIR,
    user: "ash",
    password,
    port,
    persistent: true,
    authMethod: "scram-sha-256",
    initdbFlags: ["--encoding=UTF8", "--locale=C"],
    postgresFlags: ["-c", "listen_addresses=127.0.0.1", "-c", "max_connections=60"],
    onLog: () => {},
    onError: (e) => {
      const text = String(e instanceof Error ? e.message : e);
      if (/error|fatal|panic/i.test(text)) console.error(text.trim());
    },
  });

  if (!existsSync(path.join(DATA_DIR, "PG_VERSION"))) {
    log("Initialising a new Postgres 17 cluster in .data/postgres …");
    await pg.initialise();
  }
  await pg.start();
  log(`Postgres 17 running on 127.0.0.1:${port}`);

  const admin = new Client({ host: "127.0.0.1", port, user: "ash", password, database: "postgres" });
  await admin.connect();
  const exists = await admin.query("SELECT 1 FROM pg_database WHERE datname = 'ash'");
  if (exists.rowCount === 0) {
    await admin.query("CREATE DATABASE ash");
    log("Created database 'ash'.");
  }
  await admin.end();
  return pg;
}

async function runMigrations() {
  const client = new Client({ connectionString: process.env.DATABASE_URL });
  await client.connect();
  await migrate(drizzle({ client, casing: "snake_case" }), { migrationsFolder: path.join(ROOT, "drizzle") });
  await client.end();
  log("Migrations applied.");
}

async function runSeed(force = false) {
  const { seed } = await import("../src/db/seed");
  await seed({ force });
}

/* ----------------------------------------------------------------------- main */

let child: ChildProcess | null = null;
let pg: EmbeddedPostgres | null = null;

async function shutdown(code = 0) {
  if (child && !child.killed) child.kill("SIGINT");
  if (pg) {
    log("Stopping Postgres …");
    await pg.stop().catch(() => {});
  }
  process.exit(code);
}

process.on("SIGINT", () => void shutdown(0));
process.on("SIGTERM", () => void shutdown(0));

async function main() {
  ensureEnvFile();
  pg = await startPostgres();

  if (mode === "db") {
    await runMigrations();
    log("Database ready. Press Ctrl+C to stop.");
    return; // keep the process (and Postgres) alive
  }

  await runMigrations();
  if (mode === "migrate") return shutdown(0);
  if (mode === "seed" || mode === "reset-seed") {
    await runSeed(mode === "reset-seed");
    return shutdown(0);
  }

  await runSeed(false);

  const nextBin = path.join(ROOT, "node_modules", "next", "dist", "bin", "next");
  const args = mode === "start" ? ["start", "--port", String(APP_PORT)] : ["dev", "--port", String(APP_PORT)];
  log(`Starting Next.js (${mode}) on http://localhost:${APP_PORT} …`);
  child = spawn("node", [nextBin, ...args], { cwd: ROOT, stdio: "inherit", env: process.env });
  child.on("exit", (code) => void shutdown(code ?? 0));
  scheduleMaintenance();
}

/** Local stand-in for the production scheduler: retries notifications and releases unpaid seats. */
function scheduleMaintenance() {
  const secret = process.env.CRON_SECRET;
  if (!secret) return;
  const run = () =>
    fetch(`http://localhost:${APP_PORT}/api/cron/maintenance`, { method: "POST", headers: { Authorization: `Bearer ${secret}` } })
      .then((r) => (r.ok ? r.json() : null))
      .then((report: Record<string, number | string | boolean> | null) => {
        // Only log runs that actually did something.
        const done = report && Object.entries(report).filter(([k, v]) => k !== "ok" && k !== "ms" && (v === true || (typeof v === "number" && v > 0) || v === "error"));
        if (done?.length) log(`Maintenance: ${done.map(([k, v]) => `${k}=${v}`).join(", ")}`);
      })
      .catch(() => {}); // server still starting
  setTimeout(run, 60_000);
  setInterval(run, 10 * 60_000);
}

main().catch(async (err) => {
  console.error(err);
  await shutdown(1);
});
